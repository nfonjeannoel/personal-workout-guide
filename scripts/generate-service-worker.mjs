import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";

const root = process.cwd();
const publicDirectory = join(root, "public");
const attribution = JSON.parse(await readFile(join(root, "src", "data", "image-attribution.json"), "utf8"));

async function publicFiles(directory) {
  const output = [];
  for (const name of await readdir(directory)) {
    const absolute = join(directory, name);
    const info = await stat(absolute);
    if (info.isDirectory()) output.push(...await publicFiles(absolute));
    else if (!name.endsWith(".map") && name !== "sw.js") output.push(`/${relative(publicDirectory, absolute).split(sep).join("/")}`);
  }
  return output;
}

const routes = ["/", "/workout", "/exercises", "/my-training", "/progression", "/guides", "/about", "/sources", "/account", ...Array.from({ length: 7 }, (_, index) => `/workout/day-${index + 1}`), ...attribution.map((item) => `/exercises/${item.slug}`)];
const precache = [...new Set([...routes, ...await publicFiles(publicDirectory)])];
const version = `ff-${Date.now()}`;
const core = ["/", "/workout", "/exercises", "/my-training", "/progression", "/guides", "/manifest.webmanifest", "/icon.svg"];

const source = `/* Generated by scripts/generate-service-worker.mjs. */
const CACHE = ${JSON.stringify(version)};
const PRECACHE = ${JSON.stringify(precache)};
const CORE = ${JSON.stringify(core)};

async function cacheResources(resources) {
  const cache = await caches.open(CACHE);
  for (let index = 0; index < resources.length; index += 20) {
    await Promise.allSettled(resources.slice(index, index + 20).map(async (url) => {
      const response = await fetch(url, { cache: "reload" });
      if (response.ok) await cache.put(url, response);
    }));
  }
}

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    await cacheResources(CORE);
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    await Promise.all((await caches.keys()).filter((key) => key.startsWith("ff-") && key !== CACHE).map((key) => caches.delete(key)));
    await self.clients.claim();
  })());
});

self.addEventListener("message", (event) => {
  if (event.data === "CACHE_COMPLETE_GUIDE") event.waitUntil(cacheResources(PRECACHE));
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== self.location.origin || url.pathname.startsWith("/api/")) return;

  if (request.mode === "navigate") {
    event.respondWith((async () => {
      try {
        const response = await fetch(request);
        if (response.ok) (await caches.open(CACHE)).put(request, response.clone());
        return response;
      } catch {
        return (await caches.match(request)) || (await caches.match(url.pathname)) || (await caches.match("/"));
      }
    })());
    return;
  }

  event.respondWith((async () => {
    const cached = await caches.match(request);
    if (cached) return cached;
    try {
      const response = await fetch(request);
      if (response.ok) (await caches.open(CACHE)).put(request, response.clone());
      return response;
    } catch {
      if (url.pathname === "/_next/image") {
        const sourceUrl = url.searchParams.get("url");
        if (sourceUrl) {
          const original = await caches.match(sourceUrl);
          if (original) return original;
        }
      }
      return Response.error();
    }
  })());
});
`;

await writeFile(join(publicDirectory, "sw.js"), source);
console.log(`Generated service worker with ${precache.length} offline resources.`);
